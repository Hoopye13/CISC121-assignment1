# Odd Occuences In Array
# this function will return value of any numbers that occur an odd numbers of times in an array

def solution(A):
  odd_occurences = [] # creates an empty list to add the integers to

  for integer in range(min(A), max(A)+1): # runs from the smallest to the highest number in the list
    if A.count(integer)%2 != 0: # checks if the number occurs an odd numbre of times
      odd_occurences.append(integer) # adds that number to the odd occurences list

  return odd_occurences # returns the integers that appear an odd number of times within the list

print(solution([9, 3, 9, 3, 9, 7, 9]))

