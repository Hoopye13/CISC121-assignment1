# Frog Jump
# this function will calculate the number of jumps a frog takes based on the distance its travelling and it jump distance

def solution(X, Y, D):
  distance_travelled = X # the value for how far the frogs gone
  jumps = 0 # the number of jumps the frog takes

  while distance_travelled < Y: # adds 1 jump and the distance until its greater or equal to than the destination
    distance_travelled += D
    jumps += 1

  return jumps

print(solution(10, 85, 30))